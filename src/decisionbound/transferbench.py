"""Deterministic, non-LLM transfer-decision benchmarking and safe baselines.

This is a research *instrument*, not evidence of empirical improvement.
Oracle labels are independently authored data; they cannot be generated by the
candidate policy being evaluated. Models, model prices, tool costs and verified
software outcomes are deliberately not inferred from these fixture labels.
"""
from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import random
from typing import Any

from .models import Decision, Project
from .transfer import ConservativeTransferPolicy

ACTIONS = frozenset({'apply', 'translate', 'abstain', 'escalate'})
METHODS = ('no-transfer', 'full-transfer', 'tags-only', 'decisionbound')


@dataclass(frozen=True)
class TransferCase:
    """One oracle-labeled transfer opportunity and independent target context.

    ``repo_family`` is the target repository family used for cluster bootstrap.
    ``allowed_actions`` is established independently of the tested policy.
    ``policy_conflict`` means an unjustified action could violate owner policy;
    it is NOT a claim that a real code change or real regression occurred.
    """

    case_id: str
    split: str
    repo_family: str
    target: Project
    decision: Decision
    forbidden_ids: tuple[str, ...]
    allowed_actions: frozenset[str]
    policy_conflict: bool
    label_reason: str


def load_cases(path: str | Path) -> tuple[TransferCase, ...]:
    """Load bounded JSONL labels and validate held-out repository disjointness.

    The format is versioned as ``transferbench-case-v1``. Unknown fields or
    invalid actions fail closed; no arbitrary Python or YAML objects are read.
    """
    file = Path(path).expanduser()
    if file.is_symlink() or not file.is_file() or file.stat().st_size > 2_000_000:
        raise ValueError('Benchmark must be a regular JSONL file below 2 MB')
    cases: list[TransferCase] = []
    seen = set()
    for number, line in enumerate(file.read_text(encoding='utf-8').splitlines(), 1):
        if not line.strip():
            continue
        if len(cases) >= 2000:
            raise ValueError('Benchmark contains more than 2000 cases')
        try:
            obj = json.loads(line)
            if set(obj) != {'format', 'case_id', 'split', 'repo_family', 'target',
                            'decision', 'forbidden_ids', 'allowed_actions',
                            'policy_conflict', 'label_reason'}:
                raise ValueError('Unknown or missing benchmark keys')
            if obj['format'] != 'transferbench-case-v1' or obj['split'] not in ('train', 'test'):
                raise ValueError('Unsupported benchmark version or split')
            if not isinstance(obj['case_id'], str) or not 1 <= len(obj['case_id']) <= 128:
                raise ValueError('Invalid case ID')
            if obj['case_id'] in seen:
                raise ValueError('Duplicate case ID')
            if not isinstance(obj['repo_family'], str) or not 1 <= len(obj['repo_family']) <= 100:
                raise ValueError('Invalid repository family')
            if not isinstance(obj['policy_conflict'], bool):
                raise ValueError('Conflict label must be boolean')
            if not isinstance(obj['label_reason'], str) or not obj['label_reason'].strip():
                raise ValueError('Independent oracle label rationale is required')
            if (not isinstance(obj['allowed_actions'], list) or not obj['allowed_actions'] or
                not set(obj['allowed_actions']) <= ACTIONS or
                len(set(obj['allowed_actions'])) != len(obj['allowed_actions'])):
                raise ValueError('Invalid allowed-action labels')
            if (not isinstance(obj['forbidden_ids'], list) or
                any(not isinstance(v, str) for v in obj['forbidden_ids'])):
                raise ValueError('Invalid forbidden IDs')
            target = Project(**{**obj['target'], 'technologies': tuple(obj['target'].get('technologies', ()))})
            decision = Decision.from_dict(obj['decision'])
            if decision.status not in ('candidate', 'approved', 'revoked'):
                raise ValueError('Invalid decision status')
            if decision.scope not in ('personal', 'project'):
                raise ValueError('Invalid decision scope')
            case = TransferCase(obj['case_id'], obj['split'], obj['repo_family'],
                target, decision, tuple(obj['forbidden_ids']), frozenset(obj['allowed_actions']),
                obj['policy_conflict'], obj['label_reason'])
        except (ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
            raise ValueError(f'Invalid benchmark record at line {number}') from exc
        seen.add(case.case_id)
        cases.append(case)
    if not cases:
        raise ValueError('Benchmark dataset is empty')
    train = {c.repo_family for c in cases if c.split == 'train'}
    test = {c.repo_family for c in cases if c.split == 'test'}
    if train & test:
        raise ValueError('Repository-family leakage between train and test splits')
    return tuple(cases)


def predict(method: str, case: TransferCase) -> str:
    """Return one policy action without using the oracle label or label rationale."""
    if method not in METHODS:
        raise ValueError('Unknown baseline policy')
    if method == 'no-transfer':
        return 'abstain'
    if method == 'full-transfer':
        return 'apply' if case.decision.status == 'approved' else 'abstain'
    if method == 'tags-only':
        tags = set(case.target.technologies)
        if case.decision.status != 'approved' or not set(case.decision.required_tags) <= tags:
            return 'abstain'
        return 'apply'  # intentionally ignores owner, scope, blocks and provenance
    return ConservativeTransferPolicy().evaluate(case.decision, case.target, case.forbidden_ids).action


def _ratio(numerator: int, denominator: int) -> float | None:
    """Preserve empty denominators as null instead of claiming perfect scores."""
    return numerator / denominator if denominator else None


def _score(rows: list[tuple[TransferCase, str]]) -> dict[str, Any]:
    """Compute denominators explicitly; no fake software task-success metric."""
    attempted = len(rows)
    acceptable = sum(action in case.allowed_actions for case, action in rows)
    transferred = [(case, action) for case, action in rows if action in ('apply', 'translate')]
    harmful = sum(action not in case.allowed_actions for case, action in transferred)
    conflicts = [(case, action) for case, action in rows if case.policy_conflict]
    conflict_harm = sum(action in ('apply', 'translate') and action not in case.allowed_actions
                        for case, action in conflicts)
    abstentions = [case for case, action in rows if action == 'abstain']
    correct_abstentions = sum('abstain' in case.allowed_actions for case in abstentions)
    abstain_required = [(case, action) for case, action in rows if case.allowed_actions == {'abstain'}]
    recall = sum(action == 'abstain' for _, action in abstain_required)
    return {
        'cases': attempted,
        'oracle_action_acceptance': _ratio(acceptable, attempted),
        'transferred': len(transferred),
        'harmful_policy_action_count': harmful,
        'harmful_per_transfer': _ratio(harmful, len(transferred)),
        'conflict_cases': len(conflicts),
        'harmful_per_conflict_opportunity': _ratio(conflict_harm, len(conflicts)),
        'abstention_precision': _ratio(correct_abstentions, len(abstentions)),
        'abstention_recall': _ratio(recall, len(abstain_required)),
    }


def _cluster_bootstrap(rows: dict[str, list[tuple[TransferCase, str]]],
                       *, seed: int, samples: int) -> dict[str, list[float] | None]:
    """Cluster resampling at the repository-family level, deterministic by seed."""
    groups = sorted(rows)
    if len(groups) < 2:
        return {'oracle_action_acceptance_95ci': None}
    rng = random.Random(seed)
    estimates: list[float] = []
    for _ in range(samples):
        selected = [rng.choice(groups) for _ in groups]
        trials = [trial for group in selected for trial in rows[group]]
        value = _score(trials)['oracle_action_acceptance']
        if value is not None:
            estimates.append(value)
    estimates.sort()
    return {'oracle_action_acceptance_95ci': [
        estimates[int((len(estimates)-1)*0.025)],
        estimates[int((len(estimates)-1)*0.975)],
    ] if estimates else None}


def evaluate(cases: tuple[TransferCase, ...], *, split: str = 'test', seed: int = 17,
             bootstrap_samples: int = 1000) -> dict[str, Any]:
    """Evaluate fixed baseline policies; report only policy-oracle agreement.

    No model is called. No software patch is applied. Results cannot support
    claims of real verified task success, deployment reliability, or cost savings.
    """
    if split not in ('train', 'test') or not 100 <= bootstrap_samples <= 10_000:
        raise ValueError('Invalid split or bootstrap sample count')
    filtered = tuple(sorted((c for c in cases if c.split == split), key=lambda c: c.case_id))
    if not filtered:
        raise ValueError('No benchmark cases for chosen split')
    results = {}
    for method in METHODS:
        pairs = [(case, predict(method, case)) for case in filtered]
        families: dict[str, list[tuple[TransferCase, str]]] = defaultdict(list)
        for case, action in pairs:
            families[case.repo_family].append((case, action))
        results[method] = {**_score(pairs),
            **_cluster_bootstrap(families, seed=seed, samples=bootstrap_samples)}
    return {'kind': 'policy_oracle_smoke_not_empirical_agent_results',
            'split': split, 'case_count': len(filtered), 'family_count': len({c.repo_family for c in filtered}),
            'seed': seed, 'bootstrap_samples': bootstrap_samples, 'arms': results,
            'verified_software_tasks': None, 'model_cost_usd': None,
            'paper_conclusions_supported': False}
