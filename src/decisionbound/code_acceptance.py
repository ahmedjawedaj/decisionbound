"""Operator-authored, deterministic acceptance contracts for coding runs.

Contracts are *not* generated by a coding agent and do not grant authority to
edit a repository. They define independently observable constraints: permitted
and required changed files, regression commands, and bounded text predicates.
A passing contract certifies only those checks, not broad semantic correctness.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .code_models import PatchInspection, Workspace
from .code_patches import PatchPolicy


def _sha(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


@dataclass(frozen=True)
class TextPredicate:
    """A host-evaluated text condition on an approved, nonsecret source file.

    ``contains`` and ``excludes`` are literal substrings, not executable regex
    or Python expressions. File contents are never copied into durable logs.
    """

    path: str
    contains: str = ''
    excludes: str = ''

    def __post_init__(self) -> None:
        if (not self.path or not (self.contains or self.excludes) or
                len(self.contains) > 256 or len(self.excludes) > 256):
            raise ValueError('Invalid bounded text assertion')


@dataclass(frozen=True)
class TaskContract:
    """Caller-defined, versioned acceptance scope for a single coding task.

    ``allowed_paths`` is a hard upper bound on changed paths; ``required_paths``
    is a subset that *must* change. ``test_commands`` are exact argv sequences
    chosen by the operator, never inferred from model output. Only a real,
    host-controlled sandbox may certify their successful execution.

    An explicit contract cannot authorize protected paths. All supplied paths
    are validated again against the immutable host patch policy at execution.
    """

    contract_id: str
    allowed_paths: tuple[str, ...]
    required_paths: tuple[str, ...]
    test_commands: tuple[tuple[str, ...], ...]
    assertions: tuple[TextPredicate, ...]
    schema_version: str = '1.0'

    def __post_init__(self) -> None:
        if (self.schema_version != '1.0' or not 3 <= len(self.contract_id) <= 80 or
                not self.contract_id.replace('_', '').replace('-', '').isalnum()):
            raise ValueError('Invalid acceptance contract identity/version')
        if (not 1 <= len(self.allowed_paths) <= 8 or not self.required_paths or
                not set(self.required_paths) <= set(self.allowed_paths) or
                len(self.allowed_paths) != len(set(self.allowed_paths)) or
                len(self.required_paths) != len(set(self.required_paths))):
            raise ValueError('Invalid allowed/required path scope')
        if not 1 <= len(self.test_commands) <= 5:
            raise ValueError('One to five regression commands are required')
        for command in self.test_commands:
            if (not 1 <= len(command) <= 16 or
                    any(type(v) is not str or not v or len(v) > 1024 or '\x00' in v for v in command)):
                raise ValueError('Invalid test argv')
        if not 1 <= len(self.assertions) <= 12:
            raise ValueError('At least one objective text predicate is required')
        if any(x.path not in self.allowed_paths for x in self.assertions):
            raise ValueError('Assertion path outside approved scope')

    def to_dict(self) -> dict[str, Any]:
        """Export a nonsecret, stable, JSON-compatible contract."""
        return {'schema_version': self.schema_version, 'contract_id': self.contract_id,
                'allowed_paths': list(self.allowed_paths), 'required_paths': list(self.required_paths),
                'test_commands': [list(x) for x in self.test_commands],
                'assertions': [{'path': x.path, 'contains': x.contains, 'excludes': x.excludes}
                               for x in self.assertions]}

    @classmethod
    def from_dict(cls, obj: dict[str, Any]) -> 'TaskContract':
        """Reject unknown fields and invalid nested assertions before execution."""
        if not isinstance(obj, dict) or set(obj) != {
            'schema_version', 'contract_id', 'allowed_paths', 'required_paths', 'test_commands', 'assertions'
        }:
            raise ValueError('Contract must have exactly the published fields')
        if not all(isinstance(obj[key], list) for key in (
                'allowed_paths', 'required_paths', 'test_commands', 'assertions')):
            raise ValueError('Contract arrays must be lists')
        assertions = []
        for value in obj['assertions']:
            if not isinstance(value, dict) or set(value) != {'path', 'contains', 'excludes'}:
                raise ValueError('Unknown assertion field')
            assertions.append(TextPredicate(**value))
        if any(type(v) is not str for key in ('allowed_paths', 'required_paths') for v in obj[key]):
            raise ValueError('Paths must be strings')
        if any(type(c) is not list for c in obj['test_commands']):
            raise ValueError('Commands must be JSON arrays')
        return cls(obj['contract_id'], tuple(obj['allowed_paths']), tuple(obj['required_paths']),
                   tuple(tuple(c) for c in obj['test_commands']), tuple(assertions), obj['schema_version'])

    @property
    def sha256(self) -> str:
        """Return the fingerprint used to pin contracts across retries/resumes."""
        return _sha(self.to_dict())

    def preflight(self, workspace: Path, policy: PatchPolicy,
                  test_commands: tuple[tuple[str, ...], ...]) -> None:
        """Ensure path policy and test argv cannot be weakened by the model."""
        if test_commands != self.test_commands:
            raise ValueError('Test commands differ from the approved contract')
        for path in self.allowed_paths:
            policy.check_path(workspace, path)

    def evaluate(self, workspace: Workspace, inspection: PatchInspection) -> tuple[bool, str]:
        """Check actual changed-file scope and text predicates after test execution.

        Returns a short, source-free failure code; no raw matched text is logged.
        """
        changed = set(inspection.paths)
        if not changed <= set(self.allowed_paths) or not set(self.required_paths) <= changed:
            return False, 'changed_path_scope_mismatch'
        root = Path(workspace.path)
        policy = PatchPolicy(allowed_globs=self.allowed_paths)
        for assertion in self.assertions:
            try:
                policy.check_path(root, assertion.path)
                file = root / assertion.path
                if file.stat().st_size > 256_000:
                    return False, 'assertion_file_exceeds_limit'
                text = file.read_text(encoding='utf-8')
            except (OSError, UnicodeError, ValueError):
                return False, 'assertion_file_unreadable'
            if assertion.contains and assertion.contains not in text:
                return False, 'required_text_missing'
            if assertion.excludes and assertion.excludes in text:
                return False, 'forbidden_text_present'
        return True, 'all_declared_content_assertions_passed'
