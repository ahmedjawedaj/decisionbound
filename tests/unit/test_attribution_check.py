"""The attribution check fails on assistant authorship markers and nothing else."""
from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / 'scripts' / 'check_attribution.py'
spec = importlib.util.spec_from_file_location('check_attribution', SCRIPT)
attribution = importlib.util.module_from_spec(spec)
sys.modules['check_attribution'] = attribution
spec.loader.exec_module(attribution)

HUMAN = ('Ahmed Jawed', '80323861+ahmedjawedaj@users.noreply.github.com')


def commit(message='Fix a bug', author=HUMAN, committer=HUMAN):
    return {'sha': 'a' * 40, 'author_name': author[0], 'author_email': author[1],
            'committer_name': committer[0], 'committer_email': committer[1], 'message': message}


def test_a_clean_pull_request_passes():
    assert attribution.check([commit()], 'Add a thing', 'Explains the thing.') == []


@pytest.mark.parametrize('message', [
    'Fix it\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>',
    'Fix it\n\nco-authored-by: Claude <x@example.com>',
    'Fix it\n\nCo-Authored-By: Someone <someone@anthropic.com>',
    'Fix it\n\nClaude-Session: https://claude.ai/code/session_abc',
    'Fix it\n\nGenerated with [Claude Code](https://claude.com/claude-code)',
    'Fix it\n\nSee https://claude.ai/code/session_abc',
])
def test_assistant_trailers_and_footers_in_a_commit_fail(message):
    assert attribution.check([commit(message)])


@pytest.mark.parametrize('person', [
    ('Claude', 'noreply@anthropic.com'),
    ('claude', 'someone@example.com'),
    ('Ahmed Jawed', 'bot@anthropic.com'),
    ('Ahmed Jawed', 'bot@mail.anthropic.com'),
])
def test_an_assistant_identity_as_author_or_committer_fails(person):
    assert attribution.check([commit(author=person)])
    assert attribution.check([commit(committer=person)])


def test_the_title_and_body_are_checked():
    footer = '_Generated by [Claude Code](https://claude.com/claude-code)_'
    assert attribution.check([commit()], body='Text\n\n' + footer)
    assert attribution.check([commit()], title='Co-Authored-By: Claude <a@b.c>')


def test_plain_mentions_of_the_model_are_allowed():
    message = 'Add a Claude style JSON adapter\n\nThe adapter speaks the Anthropic messages format.'
    assert attribution.check([commit(message)], 'Claude adapter', 'Adds the adapter for Anthropic-style JSON.') == []


def test_a_person_with_a_name_that_only_starts_like_claude_is_not_flagged():
    assert attribution.check([commit(author=('Claudette Martin', 'claudette@example.com'))]) == []


def git(repo, *args, env=None):
    return subprocess.run(['git', '-C', str(repo), *args], check=True, capture_output=True, text=True, env=env).stdout


def make_commit(repo, name, email, message, filename):
    (repo / filename).write_text(filename)
    git(repo, 'add', filename)
    git(repo, '-c', f'user.name={name}', '-c', f'user.email={email}', 'commit', '-q', '-m', message)
    return git(repo, 'rev-parse', 'HEAD').strip()


def test_the_git_range_reader_finds_a_trailer_in_a_real_repository(tmp_path):
    git(tmp_path, 'init', '-q')
    base = make_commit(tmp_path, *HUMAN, 'Base', 'a.txt')
    good = make_commit(tmp_path, *HUMAN, 'Good commit', 'b.txt')
    bad = make_commit(tmp_path, *HUMAN, 'Bad commit\n\nCo-Authored-By: Claude <noreply@anthropic.com>', 'c.txt')
    assert [c['message'].splitlines()[0] for c in _in(tmp_path, base, bad)] == ['Bad commit', 'Good commit']
    assert attribution.check(_in(tmp_path, base, good)) == []
    problems = attribution.check(_in(tmp_path, base, bad))
    assert len(problems) == 1 and bad[:7] in problems[0]


def _in(repo, base, head):
    import os
    old = os.getcwd()
    os.chdir(repo)
    try:
        return attribution.read_commits(base, head)
    finally:
        os.chdir(old)


def test_the_command_needs_both_shas(monkeypatch):
    monkeypatch.delenv('BASE_SHA', raising=False)
    monkeypatch.delenv('HEAD_SHA', raising=False)
    assert attribution.main() == 2


@pytest.mark.parametrize('text', [
    'Generated by Claude Code',
    'Generated by [Claude Code](https://claude.com/claude-code)',
    'Generated  with\n[Claude Code]',
    'Generated\u00a0with Claude Code',
    'See https://claude.com/code/session_abc',
    'Co-Authored-By : Claude <noreply@anthropic.com>',
    'Co-Authored-By: Cl\u200baude <bot@example.com>',
    'Generated with [Cl\u200baude Code]',
    'Claude-Session : abc',
])
def test_spacing_and_invisible_character_variants_are_caught(text):
    assert attribution.check([commit('Fix\n\n' + text)])
    assert attribution.check([commit()], body=text)


def test_prose_about_generated_fixtures_is_not_a_footer():
    assert attribution.check([commit('Add fixtures generated with Claude Sonnet')], body='Fixtures generated with Claude Sonnet 4.') == []


def test_dependabot_text_is_skipped_but_identities_are_still_checked():
    quoted = 'Release notes\n\nCo-Authored-By: Claude <noreply@anthropic.com>'
    assert attribution.check([commit(quoted)], body=quoted, check_text=False) == []
    assert attribution.check([commit(author=('Claude', 'noreply@anthropic.com'))], check_text=False)


def test_a_shallow_clone_is_unshallowed_so_no_commit_is_skipped(tmp_path):
    origin = tmp_path / 'origin'
    origin.mkdir()
    git(origin, 'init', '-q')
    base = make_commit(origin, *HUMAN, 'Base', 'a.txt')
    make_commit(origin, *HUMAN, 'Skipped by a shallow log\n\nCo-Authored-By: Claude <noreply@anthropic.com>', 'b.txt')
    head = make_commit(origin, *HUMAN, 'Head', 'c.txt')
    clone = tmp_path / 'clone'
    subprocess.run(['git', 'clone', '-q', '--depth', '1', origin.as_uri(), str(clone)], check=True, capture_output=True)
    assert git(clone, 'rev-parse', '--is-shallow-repository').strip() == 'true'
    commits = _in(clone, base, head)
    assert len(commits) == 2 and attribution.check(commits)


def test_a_shallow_clone_that_cannot_be_completed_fails_closed(tmp_path):
    origin = tmp_path / 'origin'
    origin.mkdir()
    git(origin, 'init', '-q')
    base = make_commit(origin, *HUMAN, 'Base', 'a.txt')
    make_commit(origin, *HUMAN, 'Middle', 'b.txt')
    head = make_commit(origin, *HUMAN, 'Head', 'c.txt')
    clone = tmp_path / 'clone'
    subprocess.run(['git', 'clone', '-q', '--depth', '1', origin.as_uri(), str(clone)], check=True, capture_output=True)
    git(clone, 'remote', 'remove', 'origin')
    with pytest.raises(subprocess.CalledProcessError):
        _in(clone, base, head)
